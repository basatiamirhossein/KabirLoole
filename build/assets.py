"""Build-time assets: the stylesheet (font rules + minified source), file:// fonts and the JS bundle."""

from __future__ import annotations

import base64
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Final

from data import DEFAULT_LANG, FALLBACK_STACK, FONT_FACES, LANGS, TYPEFACES, Typeface

ROOT: Final[Path] = Path(__file__).resolve().parent.parent
FONTS_DIR: Final[Path] = ROOT / "assets" / "fonts"
CSS_SRC: Final[Path] = ROOT / "src" / "css" / "main.css"
CSS_OUT: Final[Path] = ROOT / "assets" / "css" / "main.css"
EMBEDDED_FONTS_OUT: Final[Path] = ROOT / "assets" / "css" / "fonts-embedded.css"
TS_DIR: Final[Path] = ROOT / "src" / "ts"
JS_OUT: Final[Path] = ROOT / "assets" / "js" / "main.js"
BANNER: Final[str] = "/*! Kabirloole. Generated by build/build.py; edit src/ instead. */\n"


def check_fonts() -> None:
    missing = [f.file for f in FONT_FACES if not (FONTS_DIR / f"{f.file}.woff2").is_file()]
    known = {f.file for f in FONT_FACES}
    unknown = [file for tf in TYPEFACES.values() for file in tf.preload if file not in known]
    if missing or unknown:
        raise SystemExit(f"Font config error. Missing files: {missing}; preloads not in FONT_FACES: {unknown}")


# ---------------------------------------------------------------- CSS

def _font_face(family: str, src: str, weight: int, unicode_range: str) -> str:
    rng = f";unicode-range:{unicode_range.replace(' ', '')}" if unicode_range else ""
    return f'@font-face{{font-family:"{family}";src:url({src}) format("woff2");font-weight:{weight};font-display:swap{rng}}}'


def _typeface_vars(tf: Typeface) -> str:
    return (
        f"--font-body:{tf.body},{FALLBACK_STACK};"
        f"--font-display:{tf.display},{FALLBACK_STACK};"
        f"--display-weight:{tf.display_weight}"
    )


def font_css() -> str:
    faces = "".join(_font_face(f.family, f"../fonts/{f.file}.woff2", f.weight, f.unicode_range) for f in FONT_FACES)
    base = TYPEFACES[DEFAULT_LANG]
    overrides = "".join(
        f":root:lang({lang}){{{_typeface_vars(TYPEFACES[lang])}}}" for lang in LANGS if TYPEFACES[lang] != base
    )
    return f"{faces}:root{{{_typeface_vars(base)}}}{overrides}"


_STRING: Final[re.Pattern[str]] = re.compile(r"\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'")


def _minify_code(code: str) -> str:
    code = re.sub(r"\s+", " ", code)
    code = re.sub(r"\s*([{};,])\s*", r"\1", code)
    code = re.sub(r":\s+", ":", code)  # "a :hover" keeps its space; only the space after a colon goes
    return code.replace(";}", "}")


def minify_css(css: str) -> str:
    """Strip comments and whitespace, leaving quoted strings untouched."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out: list[str] = []
    pos = 0
    for match in _STRING.finditer(css):
        out.append(_minify_code(css[pos:match.start()]))
        out.append(match.group(0))
        pos = match.end()
    out.append(_minify_code(css[pos:]))
    return "".join(out).strip()


def build_css() -> int:
    css = BANNER + minify_css(font_css() + CSS_SRC.read_text(encoding="utf-8")) + "\n"
    CSS_OUT.write_text(css, encoding="utf-8")
    return len(css.encode("utf-8"))


def build_embedded_fonts() -> int:
    """Browsers refuse web fonts over file://, so a page opened from the folder loads them as data URIs."""
    rules = "\n".join(
        _font_face(
            f.family,
            "data:font/woff2;base64," + base64.b64encode((FONTS_DIR / f"{f.file}.woff2").read_bytes()).decode("ascii"),
            f.weight,
            f.unicode_range,
        )
        for f in FONT_FACES
    )
    EMBEDDED_FONTS_OUT.write_text(f"{BANNER}{rules}\n", encoding="utf-8")
    return EMBEDDED_FONTS_OUT.stat().st_size


# ---------------------------------------------------------------- JS

def _ts_files() -> list[str]:
    config = json.loads((TS_DIR / "tsconfig.json").read_text(encoding="utf-8"))
    files = config.get("files")
    if not isinstance(files, list) or not all(isinstance(f, str) for f in files):
        raise SystemExit("src/ts/tsconfig.json must list its files in load order.")
    return [str(f) for f in files]


def build_js() -> int | None:
    """Compile src/ts with any tsc on PATH and bundle it into one IIFE. Returns None when tsc is missing."""
    tsc = shutil.which("tsc")
    if tsc is None:
        return None
    with tempfile.TemporaryDirectory(prefix="kl-ts-") as tmp:
        out_dir = Path(tmp)
        result = subprocess.run([tsc, "-p", str(TS_DIR), "--outDir", str(out_dir)], capture_output=True, text=True, check=False)
        if result.returncode != 0:
            raise SystemExit(f"TypeScript compilation failed:\n{result.stdout}{result.stderr}")
        parts = []
        for name in _ts_files():
            code = (out_dir / Path(name).with_suffix(".js")).read_text(encoding="utf-8")
            code = code.replace('"use strict";\n', "", 1)
            parts.append("\n".join(line.strip() for line in code.splitlines() if line.strip()))
    body = "\n".join(parts)
    JS_OUT.parent.mkdir(parents=True, exist_ok=True)
    JS_OUT.write_text(f'{BANNER}(function(){{"use strict";\n{body}\n}})();\n', encoding="utf-8")
    return JS_OUT.stat().st_size
